import { expect, test } from '@playwright/test'

test('edge rail, full-size dialogs, groups and privacy work without chat popups', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/e2e/fixtures/personal-space.html')
  await expect(page.locator('.server-header')).toBeVisible()
  await expect(page.locator('.community-navigation')).toHaveCount(0)
  await page.mouse.move(2, 380)
  await expect(page.getByRole('navigation', { name: 'Личное пространство', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Личные сообщения', exact: true }).click()
  await page.locator('.personal-conversation').filter({ hasText: 'Лера' }).click()
  await expect(page.getByText('Отлично, договорились. Позовём ещё Мишу?', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Личные сообщения', exact: true })).toHaveCount(0)
  await page.getByLabel('Сообщение в беседу').fill('Конечно, сейчас напишу ему!')
  await page.getByLabel('Сообщение в беседу').press('Enter')
  await expect(page.getByText('Конечно, сейчас напишу ему!', { exact: true })).toBeVisible()
  await page.mouse.move(2, 380); await expect(page.getByRole('button', { name: 'Личная панель' })).toHaveAttribute('aria-expanded', 'true')
  await page.screenshot({ animations: 'disabled', path: info.outputPath('personal-dialogs-desktop.png') })
  await page.mouse.move(600, 400)
  await page.getByRole('navigation', { name: 'Разделы личного пространства' }).getByRole('button', { name: 'Беседы', exact: true }).click()
  await expect(page.locator('.personal-conversation').filter({ hasText: 'Планы на выходные' })).toBeVisible()
  await expect(page.locator('.personal-conversation').filter({ hasText: 'Личный диалог' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Новая беседа', exact: true }).click()
  await page.getByLabel('Название беседы').fill('Настолки')
  await page.getByRole('checkbox', { name: 'Лера', exact: true }).check(); await page.getByRole('checkbox', { name: 'Миша', exact: true }).check()
  await page.getByRole('button', { name: 'Создать беседу', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Настолки' })).toBeVisible()
  await page.getByRole('button', { name: 'Личные настройки', exact: true }).click()
  await page.getByRole('radio', { name: /^Никто/ }).check()
  await expect(page.getByRole('radio', { name: /^Никто/ })).toBeChecked()
  await page.screenshot({ animations: 'disabled', path: info.outputPath('personal-privacy-desktop.png') })
  expect(errors).toEqual([])
})

test('member card assigns and creates roles and opens the full profile from its avatar', async ({ page }, info) => {
  await page.goto('/e2e/fixtures/personal-space.html')
  await page.getByRole('button', { name: /Лера.*Участник/ }).click()
  const card = page.getByRole('dialog', { name: 'Карточка участника' })
  await expect(card).toBeVisible()
  const initial = await card.boundingBox()
  await card.getByRole('button', { name: 'Добавить роль' }).click()
  await card.getByRole('checkbox', { name: 'Назначить роль Редакция' }).check()
  await expect(card.getByRole('button', { name: 'Снять роль Друзья' })).toBeVisible()
  await expect(card.getByRole('button', { name: 'Снять роль Редакция' })).toBeVisible()
  await card.getByRole('button', { name: 'Создать новую роль' }).click()
  await card.getByLabel('Название роли').fill('Настольщики')
  await card.getByRole('button', { name: 'Создать и назначить' }).click()
  await expect(card.getByRole('button', { name: 'Снять роль Настольщики' })).toBeVisible()
  const after = await card.boundingBox(); expect(after?.x).toBe(initial?.x)
  await page.screenshot({ animations: 'disabled', path: info.outputPath('member-card-roles.png') })
  await card.getByRole('button', { name: 'Открыть профиль Лера' }).click()
  await expect(page.getByRole('dialog', { name: 'Полный профиль', exact: true })).toBeVisible()
})

